/**
 * Build a catalog from the current ~/.aws/config and ~/.aws/credentials
 * (ADR-0002, "import"). Pure: text in, catalog and report out. The command reads
 * the files, asks SSO for account names when online, and saves the result.
 *
 * Folding rules, proven on a real 48-profile estate by the retired script:
 *   - SSO profiles are grouped by (session, account, role). A hand-chosen name is
 *     kept; names made by `aws configure sso` go to `former_names`.
 *   - With only generated names, propose `<account-slug>-<role-short>`.
 *   - Static keys stay in credentials: those sections are named in the report and
 *     never read beyond their key names.
 */

import { parseIni, sectionSpans, splitHeader, type IniFile, type IniSection } from '../ini.ts';
import {
  CREDENTIAL_KEYS,
  validateCatalog,
  type Catalog,
  type CatalogProfile,
  type IniValue,
} from './schema.ts';

export type ImportInput = {
  configText: string;
  credentialsText: string;
  /** Account ID -> account name, from SSO `list-accounts`. Empty when offline. */
  accountNames?: ReadonlyMap<string, string>;
  /** Session to make the default; else the one most profiles use. */
  defaultSession?: string;
};

export type ImportReport = {
  /** Profiles left in credentials because they hold static keys. */
  staticProfiles: string[];
  /** Duplicates folded: the name kept, and the generated names it replaced. */
  folded: Array<{ kept: string; replaced: string[] }>;
  /** Names proposed because only generated names existed. */
  proposed: Array<{ name: string; replaced: string[] }>;
  /** Things a human should look at; none of them stop the import. */
  warnings: string[];
  /** Validation errors of the result. The catalog is still returned, to be fixed by hand. */
  errors: string[];
};

const ROLE_SHORT: Record<string, string> = {
  AdministratorAccess: 'admin',
  ReadOnlyAccess: 'read',
  ViewOnlyAccess: 'view',
  PowerUserAccess: 'power',
};

export const slug = (text: string): string =>
  text
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

export const roleShort = (role: string): string => ROLE_SHORT[role] ?? slug(role);

/** True for the names `aws configure sso` makes: `<Account>-<Role>` or `<Role>-<account id>`. */
export function isGeneratedName(name: string, role: string, accountId: string): boolean {
  if (name === 'default') return false;
  return name.endsWith(`-${role}`) || name === `${role}-${accountId}`;
}

/** `acme-prod-AdministratorAccess` -> `acme-prod`. */
function accountFromGenerated(name: string, role: string): string | undefined {
  return name.endsWith(`-${role}`) && name.length > role.length + 1 ? name.slice(0, -role.length - 1) : undefined;
}

/** A comment that is only a rule (`#####`, `-----`, `═══`) carries no group name. */
const isRule = (comment: string) => /^[#=\-*_@~ ─═]*$/.test(comment);
/** Our own generated header must not become a group on re-import. */
const isOwnHeader = (comment: string) => /^Generated by `awsx profiles|^awsx-profiles:/.test(comment);

/**
 * Group of each profile section: the last group title read before it. Sticky,
 * like the banners people write (`# ACME` then several profiles).
 *
 * A comment is a title when it is framed by a rule line, or at most three words
 * (`# OBSERVABILITY`). Longer comments are notes, not groups. Comments above a
 * non-profile block (the file's own preamble above an `[sso-session]`) are skipped.
 */
function groupsOf(text: string): Map<string, string> {
  const groups = new Map<string, string>();
  let current: string | undefined;
  for (const span of sectionSpans(text)) {
    if (profileName(span.header, true) === undefined) continue;
    const framed = span.comments.some(isRule);
    for (const comment of span.comments) {
      if (isRule(comment) || isOwnHeader(comment)) continue;
      const title = comment.replace(/^[─═\s]+|[─═#;=\-\s]+$/g, '');
      if (framed || title.split(/\s+/).length <= 3) current = title;
    }
    if (current) groups.set(span.header, current);
  }
  return groups;
}

/** Top-level keys with sub-maps folded back in: `s3 = ` + indented lines -> `{ s3: {...} }`. */
function valuesOf(section: IniSection): Record<string, IniValue> {
  const out: Record<string, IniValue> = { ...section.keys };
  for (const [key, map] of Object.entries(section.nested)) out[key] = { ...map };
  return out;
}

type Raw = {
  name: string;
  keys: Record<string, IniValue>;
  group?: string;
  /** Position in the files, to keep the first of several duplicates. */
  order: number;
};

const hasCredentialKey = (section: IniSection) => Object.keys(section.keys).some((k) => CREDENTIAL_KEYS.has(k));

function profileName(header: string, inCredentials: boolean): string | undefined {
  if (header === 'default') return 'default';
  const { type, name } = splitHeader(header);
  if (type === 'profile') return name;
  return inCredentials && type === '' ? header : undefined;
}

export function importCatalog(input: ImportInput): { catalog: Catalog; report: ImportReport } {
  const config: IniFile = parseIni(input.configText);
  const credentials: IniFile = parseIni(input.credentialsText);
  const configGroups = groupsOf(input.configText);
  const credentialGroups = groupsOf(input.credentialsText);
  const report: ImportReport = { staticProfiles: [], folded: [], proposed: [], warnings: [], errors: [] };

  const sso_sessions: Catalog['sso_sessions'] = {};
  const sections: NonNullable<Catalog['sections']> = {};
  const raw = new Map<string, Raw>();
  let order = 0;

  for (const [header, section] of config) {
    const { type, name } = splitHeader(header);
    if (type === 'sso-session') {
      sso_sessions[name] = { ...section.keys };
      continue;
    }
    const profile = profileName(header, false);
    if (profile === undefined) {
      sections[header] = valuesOf(section);
      continue;
    }
    if (hasCredentialKey(section)) {
      report.errors.push(
        `profile "${profile}": static keys in ~/.aws/config; move them to ~/.aws/credentials, then import again`,
      );
      continue;
    }
    const group = configGroups.get(header);
    raw.set(profile, { name: profile, keys: valuesOf(section), order: order++, ...(group ? { group } : {}) });
  }

  // Credentials second: its keys win, as in the CLI (ADR-0002, decision 1).
  for (const [header, section] of credentials) {
    const name = profileName(header, true);
    if (name === undefined) continue;
    if (hasCredentialKey(section)) {
      // Static keys stay where they are. A config part of the same profile (region,
      // output) is still imported, so apply keeps writing it.
      report.staticProfiles.push(name);
      continue;
    }
    const entry = raw.get(name) ?? { name, keys: {}, order: order++ };
    Object.assign(entry.keys, valuesOf(section));
    const group = credentialGroups.get(header);
    if (group) entry.group = group;
    raw.set(name, entry);
    report.warnings.push(
      `profile "${name}" is in ~/.aws/credentials and would shadow the generated one; remove it from there after apply`,
    );
  }

  // Default session: as asked, else the one most profiles reference.
  const uses = new Map<string, number>();
  for (const r of raw.values()) {
    const s = r.keys.sso_session;
    if (typeof s === 'string') uses.set(s, (uses.get(s) ?? 0) + 1);
  }
  let defaultSession = input.defaultSession;
  if (defaultSession === undefined) {
    let best = 0;
    for (const name of Object.keys(sso_sessions)) {
      const n = uses.get(name) ?? 0;
      if (n > best) [defaultSession, best] = [name, n];
    }
  }

  // Fold SSO profiles by (session, account, role).
  type Triple = { session: string; account: string; role: string; members: Raw[] };
  const triples = new Map<string, Triple>();
  const others: Raw[] = [];
  for (const r of raw.values()) {
    const { sso_session: session, sso_account_id: account, sso_role_name: role } = r.keys;
    if (typeof session === 'string' && typeof account === 'string' && typeof role === 'string') {
      const key = `${session}\u0000${account}\u0000${role}`;
      const t = triples.get(key) ?? { session, account, role, members: [] };
      t.members.push(r);
      triples.set(key, t);
    } else {
      others.push(r);
    }
  }

  const taken = new Set<string>([...raw.keys()]);
  const unique = (base: string) => {
    let name = base;
    for (let i = 2; taken.has(name); i++) name = `${base}-${i}`;
    taken.add(name);
    return name;
  };

  const profiles: CatalogProfile[] = [];
  const toEntry = (name: string, r: Raw, sso?: Triple, accountName?: string): CatalogProfile => {
    const keys = { ...r.keys };
    const entry: CatalogProfile = { name };
    if (r.group) entry.group = r.group;
    if (accountName) entry.account_name = accountName;
    if (sso) {
      delete keys.sso_session;
      delete keys.sso_account_id;
      delete keys.sso_role_name;
      entry.account_id = sso.account;
      entry.role = sso.role;
    }
    const region = keys.region;
    if (typeof region === 'string') {
      entry.region = region;
      delete keys.region;
    }
    if (sso && sso.session !== defaultSession) entry.session = sso.session;
    if (Object.keys(keys).length > 0) entry.extra = keys;
    return entry;
  };

  for (const t of triples.values()) {
    const members = [...t.members].sort((a, b) => a.order - b.order);
    const chosen = members.filter((m) => !isGeneratedName(m.name, t.role, t.account));
    const generated = members.filter((m) => isGeneratedName(m.name, t.role, t.account)).map((m) => m.name);
    const accountName =
      input.accountNames?.get(t.account) ??
      generated.map((n) => accountFromGenerated(n, t.role)).find((n) => n !== undefined);

    const regions = new Set(members.map((m) => m.keys.region).filter((x) => x !== undefined));
    if (members.length > 1 && regions.size > 1) {
      report.warnings.push(
        `${members.map((m) => `"${m.name}"`).join(', ')} are the same account and role with different regions; kept ${JSON.stringify(
          (chosen[0] ?? members[0])?.keys.region,
        )}`,
      );
    }

    if (chosen.length > 0) {
      chosen.forEach((m, i) => {
        const entry = toEntry(m.name, m, t, accountName);
        if (i === 0 && generated.length > 0) {
          entry.former_names = generated;
          report.folded.push({ kept: m.name, replaced: generated });
        }
        profiles.push(entry);
      });
      if (chosen.length > 1) {
        report.warnings.push(
          `${chosen.map((m) => `"${m.name}"`).join(', ')} are the same account and role under hand-chosen names; keep one`,
        );
      }
    } else {
      const first = members[0] as Raw;
      for (const n of generated) taken.delete(n);
      const base = `${accountName ? slug(accountName) : t.account.slice(-4)}-${roleShort(t.role)}`;
      const name = unique(base);
      const entry = toEntry(name, first, t, accountName);
      entry.former_names = generated;
      report.proposed.push({ name, replaced: generated });
      profiles.push(entry);
    }
  }
  for (const r of others) profiles.push(toEntry(r.name, r));

  // A string value every profile shares (cli_pager = , output = json) becomes a default.
  const defaults: Catalog['defaults'] = {};
  if (defaultSession !== undefined) defaults.sso_session = defaultSession;
  if (profiles.length > 1) {
    const first = profiles[0]?.extra ?? {};
    for (const [key, value] of Object.entries(first)) {
      if (typeof value !== 'string' || key === 'role_arn' || key === 'source_profile') continue;
      if (profiles.every((p) => p.extra?.[key] === value)) {
        defaults[key] = value;
        for (const p of profiles) {
          delete p.extra?.[key];
          if (p.extra && Object.keys(p.extra).length === 0) delete p.extra;
        }
      }
    }
  }

  profiles.sort(
    (a, b) =>
      Number(b.name === 'default') - Number(a.name === 'default') ||
      (a.group ?? '').localeCompare(b.group ?? '') ||
      a.name.localeCompare(b.name),
  );
  report.staticProfiles.sort();

  const catalog: Catalog = { version: 1, sso_sessions, defaults, profiles };
  if (Object.keys(sections).length > 0) catalog.sections = sections;

  const validation = validateCatalog(catalog, { externalProfiles: new Set(report.staticProfiles) });
  report.errors.push(...validation.errors);
  return { catalog, report };
}
