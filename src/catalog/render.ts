/**
 * Render ~/.aws/config from the catalog (ADR-0002, "Rendering").
 *
 * The output is deterministic, so diffs between two applies are meaningful and
 * the drift hash is stable. The header carries a sha256 of the body: if the body
 * no longer matches it, someone edited the file outside the catalog.
 */

import { createHash } from 'node:crypto';
import { valueProblem, type Catalog, type CatalogProfile, type IniValue } from './schema.ts';

const HEADER = '# Generated by `awsx profiles apply` from the profile catalog. Edit the catalog, not this file.';
const HASH_PREFIX = '# awsx-profiles: sha256=';

/** `key = value`, `key =` for an empty value, or `key =` plus indented lines for a sub-map. */
function formatEntry(key: string, value: IniValue): string[] {
  if (typeof value === 'string') {
    // Validation already rejects these; this is the last guard before the file.
    const problem = valueProblem(value);
    if (problem) throw new Error(`refusing to write ${key}: value ${problem}`);
    return [value === '' ? `${key} =` : `${key} = ${value}`];
  }
  return [`${key} =`, ...Object.entries(value).flatMap(([sub, v]) => formatEntry(sub, v).map((l) => `  ${l}`))];
}

function block(header: string, keys: Record<string, IniValue>): string[] {
  return [`[${header}]`, ...Object.entries(keys).flatMap(([k, v]) => formatEntry(k, v)), ''];
}

/** Keys of one profile, in the order the ADR fixes. */
export function profileKeys(profile: CatalogProfile, catalog: Catalog): Record<string, IniValue> {
  const keys: Record<string, IniValue> = {};
  if (profile.account_id !== undefined && profile.role !== undefined) {
    const session = profile.session ?? catalog.defaults.sso_session;
    if (session !== undefined) keys.sso_session = session;
    keys.sso_account_id = profile.account_id;
    keys.sso_role_name = profile.role;
  }
  if (profile.region !== undefined) keys.region = profile.region;
  for (const [k, v] of Object.entries(catalog.defaults)) if (k !== 'sso_session') keys[k] = v;
  Object.assign(keys, profile.extra ?? {});
  return keys;
}

/**
 * Profiles grouped by `group`: ungrouped first (so none sits under another
 * group's banner), then each group in order of first appearance, catalog order
 * inside a group.
 */
export function groupProfiles(profiles: CatalogProfile[]): Array<{ group?: string; profiles: CatalogProfile[] }> {
  const groups = new Map<string | undefined, CatalogProfile[]>([[undefined, []]]);
  for (const p of profiles) {
    const list = groups.get(p.group) ?? [];
    list.push(p);
    groups.set(p.group, list);
  }
  return [...groups]
    .filter(([, list]) => list.length > 0)
    .map(([group, list]) => (group === undefined ? { profiles: list } : { group, profiles: list }));
}

function renderBody(catalog: Catalog): string {
  const out: string[] = [];
  for (const [name, keys] of Object.entries(catalog.sso_sessions)) out.push(...block(`sso-session ${name}`, keys));
  for (const [header, keys] of Object.entries(catalog.sections ?? {})) out.push(...block(header, keys));
  for (const { group, profiles } of groupProfiles(catalog.profiles)) {
    if (group !== undefined) out.push(`# ── ${group} ──`, '');
    for (const p of profiles) out.push(...block(`profile ${p.name}`, profileKeys(p, catalog)));
  }
  return out.join('\n');
}

const sha256 = (text: string) => createHash('sha256').update(text).digest('hex');

export function renderConfig(catalog: Catalog): string {
  const body = renderBody(catalog);
  return `${HEADER}\n${HASH_PREFIX}${sha256(body)}\n\n${body}`;
}

export type GeneratedState =
  /** Generated by us and untouched since. */
  | { state: 'clean' }
  /** Generated by us, then edited: the body no longer matches the recorded hash. */
  | { state: 'edited' }
  /** No awsx header at all: hand-written, or made by another tool. */
  | { state: 'unmanaged' };

/** Was this config file generated by `apply`, and is it still as generated? */
export function inspectGenerated(text: string): GeneratedState {
  const match = /^[^\n]*\n# awsx-profiles: sha256=([0-9a-f]{64})\n\n/.exec(text);
  if (!match) return { state: 'unmanaged' };
  const body = text.slice(match[0].length);
  return sha256(body) === match[1] ? { state: 'clean' } : { state: 'edited' };
}
